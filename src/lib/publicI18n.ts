// Hook pro veřejné stránky — čte jazyk z localStorage
export function usePublicLang() {
  if (typeof window === 'undefined') return { lang: 'cs' as PublicLang, t: (key: string) => publicTranslations.cs[key] || key, setLang: () => {} }

  const stored = localStorage.getItem('clientoro_lang') as PublicLang | null
  const lang: PublicLang = stored && ['cs', 'sk', 'en'].includes(stored) ? stored : 'cs'

  const t = (key: string) => publicTranslations[lang]?.[key] || publicTranslations.cs[key] || key

  const setLang = (l: PublicLang) => {
    localStorage.setItem('clientoro_lang', l)
    window.location.reload()
  }

  return { lang, t, setLang }
}

